import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const source=await readFile(new URL("../../public/assets/sayo-ui.js",import.meta.url),"utf8");
const {normalizeHistory,metricState,chartModel,cycleLabel,renderCycleContext,observationText,studyReportMeta,preferenceStorage}=await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
const fixture=JSON.parse(await readFile(new URL("./producer-contract.fixture.json",import.meta.url),"utf8"));

assert.equal(metricState({current:19,is_stale:true,data_status:"fresh"}),"stale");
assert.equal(metricState({current:19,is_stale:true,data_status:"expired"}),"expired");
assert.equal(metricState({current:19,is_stale:true,data_status:"delayed"}),"delayed");
assert.equal(metricState({current:0,data_status:"fresh"}),"fresh");
assert.equal(metricState({current:false,data_status:"fresh"}),"unavailable");
assert.equal(metricState({current:19}),"unknown");
assert.equal(metricState({current:null,data_status:"fresh"}),"unavailable");
assert.equal(metricState({price:100,data_status:"market_closed"}),"market_closed");
assert.deepEqual(normalizeHistory([null,{date:"bad",value:2},{date:"2026-10-21",value:Infinity},{date:"2026-10-23",value:1},{date:"2026-10-22",value:0},{date:"2026-10-23",value:2}]),[{date:"2026-10-22",value:0},{date:"2026-10-23",value:2}]);
assert.equal(chartModel([{date:"2026-10-23",value:1}]),null);
const flat=chartModel([{date:"2026-10-22",value:3},{date:"2026-10-23",value:3}]);
assert(flat.minimum<3 && flat.maximum>3);
assert(!flat.path.includes("NaN"));
const spaced=chartModel([{date:"2026-10-01",value:1},{date:"2026-10-02",value:2},{date:"2026-10-11",value:3}]);
assert(spaced.path.includes("L92.20"),"chart x coordinate must use elapsed time, not ordinal spacing");
const history=Array.from({length:80},(_,i)=>({date:new Date(Date.UTC(2026,0,i+1)).toISOString().slice(0,10),value:i}));
assert.equal(normalizeHistory(history).length,60);
assert.equal(normalizeHistory(history)[0].value,20);
assert.equal(cycleLabel(fixture.stock),"사이클 중립 · 근거 부족");
assert.equal(cycleLabel({...fixture.stock,cycle_data_status:"latest_available"}),"사이클 중립 · 근거 부족");
assert.equal(cycleLabel({...fixture.stock,cycle_data_status:"expired"}),"사이클 갱신 대기");
const research=renderCycleContext(fixture.stock);
assert(research.includes("합성 지지 근거") && research.includes("합성 반대 근거"));
assert(research.includes("우호 → 중립 · 근거 부족"));
assert(research.includes('href="https://example.com/contrary"'));
assert(!research.includes("<p></p>"));
assert(!renderCycleContext({...fixture.stock,cycle_evidence:[{fact:"<script>alert(1)</script>",source_url:"javascript:alert(1)"}]}).includes("<script>"));
assert.equal(observationText(fixture.market_environment.series.core_pce),"2026-09 기준월");
assert.equal(metricState(fixture.market_environment.series.core_pce),"latest_available");
assert.deepEqual(studyReportMeta(fixture),{status:"fresh",quality:"insufficient",summary:"최신 관측 · 근거 부족",generated_at:"2026-10-24T08:00:00+09:00",expires_at:"2026-10-31T08:00:00+09:00"});
Object.defineProperty(globalThis,"localStorage",{configurable:true,get(){throw new Error("blocked");}});
assert.equal(preferenceStorage(),null);
delete globalThis.localStorage;
console.log("SAYO UI: freshness, history/chart, producer cycle/month-period contract, escaping, blocked preference storage passed");
