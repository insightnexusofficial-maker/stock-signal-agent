// Execute only the localhost preview: synthetic/public market data, no Firebase.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {JSDOM}=await import(process.argv[2] || 'jsdom');
const previewPath=process.argv[3] || '/private/tmp/sayo-rollback-preview/index.html';
const html=await readFile(previewPath,'utf8');
assert(!html.includes('const VAPID_KEY'));
const dom=new JSDOM(html,{url:'http://127.0.0.1:8772',runScripts:'outside-only',pretendToBeVisual:true});
dom.window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
dom.window.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new dom.window.Event('close'));};
const uiSource=await readFile(new URL('../../public/assets/sayo-ui.js',import.meta.url),'utf8');
dom.window.eval(`window.previewUi=(()=>{${uiSource.replaceAll('export function','function')}\nreturn {createSayoUI,cycleLabel,renderCycleContext};})();`);
let module=html.match(/<script type="module">([\s\S]*?)<\/script>/)[1];
assert(!module.includes('https://www.gstatic.com'));
module=module.replace(/import \{ createSayoUI, cycleLabel, renderCycleContext \} from "[^"]+";/,'const {createSayoUI,cycleLabel,renderCycleContext}=window.previewUi;');
dom.window.eval(module + `
window.rerenderPreview=()=>render(latestData); window.expirePreviewCycles=()=>render({...latestData,us_stock:latestData.us_stock.map(stock=>({...stock,cycle_status:"favorable",cycle_data_status:"expired"}))});`);
await new Promise(resolve=>setTimeout(resolve,40));
const doc=dom.window.document;
assert(doc.querySelectorAll('.stock-row').length>=3,'preview renders stock rows');
assert.equal(doc.querySelectorAll('.stock-expand-btn').length,0,'restored three-column row has no extra button');
const row=doc.querySelector('#us-stock-list .stock-row');
const header=row.querySelector('.stock-row-header');
assert.equal(header.getAttribute('aria-expanded'),'false');
header.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
assert.equal(header.getAttribute('aria-expanded'),'true');
assert(row.classList.contains('expanded'));
const favorite=row.querySelector('.favorite-btn');
favorite.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
assert(row.classList.contains('expanded'),'favorite key event must not toggle parent disclosure');
header.focus();
// Repeat the same public/synthetic render to test disclosure and focus continuity.
dom.window.rerenderPreview();
const refreshed=doc.querySelector('#us-stock-list .stock-row');
assert(refreshed.classList.contains('expanded'));
assert.equal(doc.activeElement,refreshed.querySelector('.stock-row-header'));
assert.equal(refreshed.querySelector('.stock-row-header').children.length,3);
assert(doc.querySelectorAll('.series-button').length>=4);
assert(doc.querySelector('.series-comparison').textContent.length>0);
assert(doc.querySelector('#market-overview-status').textContent.length<20);
doc.querySelector('[data-series="nfci"]').click();
assert(doc.querySelector('#metric-dialog').open);
assert.match(doc.querySelector('#metric-content').textContent,/비교 기준/);
assert.match(doc.querySelector('#metric-content').textContent,/장기 평균/);
assert.equal(doc.querySelectorAll('#metric-content .metric-reading > div').length,4);
dom.window.expirePreviewCycles();
const pendingBadge=doc.querySelector('#us-stock-list .badge.cycle-neutral');
assert.match(pendingBadge.textContent,/사이클 갱신 대기/);
assert.equal(doc.querySelectorAll('#us-stock-list .badge.cycle-favorable').length,0,'expired favorable cycle must not retain a green badge');
console.log(`SAYO preview integration: ${doc.querySelectorAll('.stock-row').length} rows, restored columns, keyboard/focus/disclosure, metric reading passed`);
dom.window.close();
